function Run-Sub([string]$Probe, [string]$Only) {
    $out = Join-Path $env:TEMP ('tc155_sub_' + [IO.Path]::GetFileNameWithoutExtension($Probe) + '.txt')
    if (Test-Path -LiteralPath $out) { Remove-Item -LiteralPath $out -Force }
    $p = Join-Path $PSScriptRoot $Probe
    & powershell -NoProfile -ExecutionPolicy Bypass -File $p -Exe $Exe -OutFile $out -Only $Only *> $null
    $lines = @(); if (Test-Path -LiteralPath $out) { $lines = @(Get-Content -LiteralPath $out); Remove-Item -LiteralPath $out -Force }
    Out ("   {0}: {1}" -f [IO.Path]::GetFileName($Probe), (@($lines | Where-Object { $_ -like 'Rows:*' }) -join ' '))
    return , $lines
}
function Check-Text($Lines, [string]$Row, [string]$Case, [string]$Want, [string]$Old) {
    $l = @($Lines | Where-Object { $_ -like ($Case + ' *RUN*') }) | Select-Object -First 1
    if (-not $l) { Row $Row 'TEXT' 'NOT DRIVEN' ("row {0} not in the result" -f $Case); return }
    $w = $(if ($Fixed) { $Want } else { $Old })
    $ok = $l.Contains($w) -and ($l -match '\s(PASS|FAIL)\s') -and -not ($l -match '\sFAIL\s')
    $i = [Math]::Max(0, $l.IndexOf('asked:')); if ($i -eq 0) { $i = [Math]::Max(0, $l.Length - 300) }
    Row $Row 'TEXT' (V $ok) ("want '{0}' (the row itself passes its own checks); {1}" -f $w, $l.Substring($i, [Math]::Min(300, $l.Length - $i)))
}

