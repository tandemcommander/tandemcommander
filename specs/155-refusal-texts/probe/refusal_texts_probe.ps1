# ---- Renamer: a link renamed onto the file it points at -------------------------------------
function Run-RenLink {
    $d = $Root + '\ren\link'; NewDir $d
    Put ($d + '\a.txt') 'TARGET'
    $r = Cmd ('mklink "{0}" "{1}"' -f ($d + '\lnk.txt'), ($d + '\a.txt'))
    if (-not [IO.File]::Exists($LP + $d + '\lnk.txt')) { Row 'ren-link' 'TEXT' 'NOT DRIVEN' ('mklink refused: ' + "$r"); return }
    $id = 0; $before = Reports
    try {
        $id = Start-P $d
        $dlg = Open-Renamer $id
        if ($dlg -eq [IntPtr]::Zero) { Row 'ren-link' 'TEXT' 'FAIL' ('the Renamer dialog did not open; ' + $script:LastOpenDiag); return }
        Set-Mask $dlg 'lnk.txt'
        $nn = Kid $dlg 106 'ComboBox'
        [void][Drv098f]::SetText($nn, 'a.txt', 5000)
        Start-Sleep -Milliseconds 1500
        Click (Kid $dlg 1 'Button')
        Start-Sleep -Milliseconds 1500
        $ans = Answer $id 20 @(6, 2) @($dlg)   # the Renamer's overwrite question: Yes (it asks first); the refusal: Cancel
        $texts = Msgs2 $ans
        $want = $(if ($Fixed) { 'Cannot move a file to itself' } else { 'already exists' })
        $kept = (Get ($d + '\a.txt')) -ceq 'TARGET' -and [IO.File]::Exists($LP + $d + '\lnk.txt')
        Row 'ren-link' 'TEXT' (V (($texts -match $want) -and $kept)) ("want '{0}'; files kept {1}; boxes: {2}; folder: {3}" -f $want, $kept, $texts, (Names $d))
        Close-Renamer $id $dlg
    }
    catch { Row 'ren-link' 'ERROR' 'FAIL' ($_.Exception.Message + ' @ ' + $_.ScriptStackTrace) }
    finally { if ($id) { End-P 'ren-link' $id $before } }
}

